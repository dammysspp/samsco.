ALTER TABLE public.works ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'published';
ALTER TABLE public.works ADD COLUMN IF NOT EXISTS "scheduledAt" TIMESTAMPTZ;
ALTER TABLE public.works ADD COLUMN IF NOT EXISTS order_index INTEGER DEFAULT 0;
ALTER TABLE public.works ADD COLUMN IF NOT EXISTS views INTEGER DEFAULT 0;
ALTER TABLE public.works ADD COLUMN IF NOT EXISTS plays INTEGER DEFAULT 0;
ALTER TABLE public.works ADD COLUMN IF NOT EXISTS clicks INTEGER DEFAULT 0;

-- 8. Create Inquiries Table for Contact Form submissions
CREATE TABLE IF NOT EXISTS public.inquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    message TEXT NOT NULL,
    status TEXT DEFAULT 'New',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

