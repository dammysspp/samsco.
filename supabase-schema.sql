-- 1. Create Skills Table
CREATE TABLE IF NOT EXISTS public.skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    level INTEGER NOT NULL CHECK (level >= 0 AND level <= 100),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Experience Table
CREATE TABLE IF NOT EXISTS public.experience (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year TEXT NOT NULL,
    title TEXT NOT NULL,
    subtitle TEXT NOT NULL,
    order_index INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Create Site Settings Table
CREATE TABLE IF NOT EXISTS public.site_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Create Categories Table
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    color TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Create Testimonials Table
CREATE TABLE IF NOT EXISTS public.testimonials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_name TEXT NOT NULL,
    client_role TEXT NOT NULL,
    company TEXT,
    content TEXT NOT NULL,
    rating INTEGER DEFAULT 5,
    order_index INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Create Works Table (with all enhanced columns)
CREATE TABLE IF NOT EXISTS public.works (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    cat TEXT,
    url TEXT NOT NULL,
    type TEXT DEFAULT 'image',
    "projectUrl" TEXT,
    client TEXT,
    year TEXT,
    role TEXT,
    desc TEXT,
    tags TEXT,
    problem TEXT,
    process TEXT,
    result TEXT,
    "demoUrl" TEXT,
    "thumbnailUrl" TEXT,
    "aspectRatio" TEXT DEFAULT '16:9',
    "focalPoint" TEXT DEFAULT 'center',
    status TEXT DEFAULT 'published',
    "scheduledAt" TIMESTAMPTZ,
    order_index INTEGER DEFAULT 0,
    views INTEGER DEFAULT 0,
    plays INTEGER DEFAULT 0,
    clicks INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Add columns if table already existed previously (Idempotent migrations)
ALTER TABLE public.categories ADD COLUMN IF NOT EXISTS color TEXT;

